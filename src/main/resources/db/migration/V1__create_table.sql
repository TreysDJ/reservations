CREATE TABLE rooms
(
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roomId BIGINT NOT NULL
);

CREATE TABLE reservations
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userId    BIGINT NOT NULL,
    roomId    BIGINT NOT NULL,
    startDate DATE   NOT NULL,
    endDate   DATE   NOT NULL
);

